def lcs(words_a, words_b):
    # Dynamic programming table for longest common subsequence length
    n = len(words_a)
    m = len(words_b)

    dp = [[0] * (m + 1) for _ in range(n + 1)]

    for i in range(1, n + 1):
        for j in range(1, m + 1):
            if words_a[i - 1] == words_b[j - 1]:
                dp[i][j] = dp[i - 1][j - 1] + 1
            else:
                dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])

    return dp[n][m]
